def word_for(week_number: int, day: int) -> Word:
    index = (week_number * 7 + day - 1) % len(WORDS)
    return WORDS[index]


def word_for_date(day: date) -> Word:
    """Одно слово на календарный день - все дети делят один вызов модели."""
    return WORDS[day.toordinal() % len(WORDS)]


def example_for(word: Word, pet_name: str) -> str:
    """Запасной пример, если модель молчит: подставляем имя питомца в готовый."""
    if "Финик" in word.example:
        return word.example.replace("Финик", pet_name)
    return pick((word.example, f"{pet_name} запомнил слово «{word.word}»."), pet_name + word.word)
